const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, es }

/** `es` for any Spanish locale (`es`, `es_ES.UTF-8`, `es-419`…), otherwise `en`. */
export function localeFrom(value: string | undefined): Locale | undefined {
  if (!value) return undefined
  const v = value.trim().toLowerCase()
  if (v === "" || v === "c" || v === "posix") return undefined
  return v.startsWith("es") ? "es" : "en"
}

export function detectLocale(env: Record<string, string | undefined> = process.env): Locale {
  for (const name of ["OPENSPEC_STATUS_LANG", "LC_ALL", "LC_MESSAGES", "LANG"]) {
    const l = localeFrom(env[name])
    if (l) return l
  }
  try {
    return localeFrom(Intl.DateTimeFormat().resolvedOptions().locale) ?? "en"
  } catch {
    return "en"
  }
}

let current: Locale = detectLocale()

export const locale = (): Locale => current
export function setLocale(l: Locale): void {
  current = l
}

/** The message for `key` in the current locale, with `{name}` placeholders filled. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const text = MESSAGES[current][key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m))
}

/** «a, b and c» / «a, b y c». */
export function listOf(items: readonly string[]): string {
  if (items.length < 2) return items.join("")
  return `${items.slice(0, -1).join(", ")} ${t("list.and")} ${items.at(-1)}`
}
